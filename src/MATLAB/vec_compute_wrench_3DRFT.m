%% vec_compute_wrench_3DRFT.m
%
% Descrption:
%   Vectorized version of compute_wrench_3DRFT.m
%
%   This function uses 3D resistive force theory (RFT) to compute the
%   ground reaction wrench (GRW) on a rigid body, given the following
%   properties of the rigid body:
%   * geometry (represented as a triangulation object)
%   * configuration (represented as an SE(3) transformation matrix)
%   * twist (represented as a 6-vector consisting of translational and
%     angular velocity components).
%   * terrain parameters (i.e., lumped dimensionless penetration resistance
%     scaling factor)
%
%   The 3D RFT algorithm comes from the following paper:
%   "Mechanistic framework for reduced-order models in soft materials:
%   Application to three-dimensional granular intrusion" by Agarwal et al.,
%   PNAS 2023.
%
% Inputs:
%   Twb: SE(3) (4x4 matrix) representation of the configuration of the rigid
%        body frame {b} in the world frame {w}.
%   Vb:  6-vector representation of rigid body's instantaneous twist,
%        expressed in {b}, the frame aligned with the body's principal axes
%        of inertia and with origin at the body's center of mass.
%   params: a struct with many fields (generated by calling init_params()).
%
% Outputs:
%   F_c: 6-vector representation of instantaneous wrench experienced by the
%        rigid body as it interacts with deformable terrain, expressed in
%        {c}, the frame aligned with the world frame and with origin at the
%        body's center of mass.

function [F_c,varargout] = vec_compute_wrench_3DRFT(Twb,Vb,params)
%% Compute twist in {c}, a frame at the COM aligned with the world
[Rwb,pwb] = TransToRp(Twb);
Rwc = eye(3);
pwc = pwb;
Twc = RpToTrans(Rwc,pwc);
Tcb = TransInv(Twc)*Twb;
Vc = Adjoint(Tcb)*Vb;

%% Update triangulation TR, given current body configuration
% transform (rotate and translate) each point in the body's
% triangulation:
default_TR = params.body.geom.TR;
points = [default_TR.Points,ones(size(default_TR.Points,1),1)]...
       * transpose(Twb)*[eye(3);zeros(1,3)];

% reconnect the transformed points according to the original triangulation:
TR = triangulation(default_TR.ConnectivityList,points);
N = size(TR,1);

%% Compute force and moment fields over surface of rigid body
% preallocate arrays for local force, moment fields and local velocity field:
areas = params.body.geom.areas;

center_c = TR.incenter';
normal_c = TR.faceNormal'; % unit normals

% extract components of spatial twist V:
omg_x = Vc(1); % angular velocity about c-frame x-axis
omg_y = Vc(2); % angular velocity about c-frame y-axis
omg_z = Vc(3); % angular velocity about c-frame z-axis
v_x   = Vc(4); % translational velocity along c-frame x-axis
v_y   = Vc(5); % translational velocity along c-frame y-axis
v_z   = Vc(6); % translational velocity along c-frame z-axis

omg_c = [omg_x*ones(1,N);
         omg_y*ones(1,N);
         omg_z*ones(1,N)];
v_com_c = [v_x*ones(1,N);
           v_y*ones(1,N);
           v_z*ones(1,N)];

% local velocity:
v_c = Twb(1:3,1:3)*v_com_c + cross(omg_c,center_c - Twb(1:3,4));
%% Compute granular drag forces on each face
% compute {c}-frame unit vectors:
%   v_hat_c: (3xN) unit velocity vector in the {c} frame
%   n_hat_c: (3xN) unit normal vector in the {c} frame
%   g_hat_c: (3xN) unit vector in direction of gravity, in the {c} frame
v_hat_c = reshape(v_c./vecnorm(v_c,2,1),[3,N]); % unit vel vector in {c}
n_hat_c = reshape(normal_c,[3,N]);
g_hat_c = [zeros(2,N);
           -ones(1,N)];

% compute coordinate-invariant dot products:
p1 = dot(g_hat_c,v_hat_c);
p2 = abs(dot(g_hat_c,n_hat_c)); % absolute value b/c Agarwal only fit over [0,1]
p3 = dot(n_hat_c,v_hat_c);

% Compute cubic polynomials from coordinate-invariant dot products:
T = [ones(1,N);
     p1;
     p2;
     p3;
     p1.^2;
     p2.^2;
     p3.^2;
     p1.*p2;
     p2.*p3;
     p3.*p1;
     p1.^3;
     p2.^3;
     p3.^3;
     p1.*(p2.^2);
     p2.*(p1.^2);
     p2.*(p3.^2);
     p3.*(p2.^2);
     p3.*(p1.^2);
     p1.*(p3.^2);
     p1.*p2.*p3];

% compute coordinate-invariant functions of cubic polynomials T:
f = params.terrain.rft.cubic_coefficients*T;

% compute traction-per-unit-depth in {c}:
tpud_c = params.terrain.scale_factor ...
       * (n_hat_c.*f(1,:) + v_hat_c.*f(2,:) + g_hat_c.*f(3,:));

% compute force in {c} frame by scaling traction-per-unit-depth by face
% area and depth:
f_c = -center_c(3,:).*areas.*tpud_c;
 
% zero force on non-submerged faces:
f_c(1,center_c(3,:) >= 0) = 0;
f_c(2,center_c(3,:) >= 0) = 0;
f_c(3,center_c(3,:) >= 0) = 0;

 % zero force on non-leading faces:
f_c(1,p3 < 0) = 0;
f_c(2,p3 < 0) = 0;
f_c(3,p3 < 0) = 0;

% compute moment about {c} due to force_c:
m_c = cross(center_c - Twb(1:3,4),f_c);

% rotational power generated/dissipated at each face:
rot_pwr = dot(omg_c,m_c);
% m_c(:,rot_pwr > 0) = 0;
rot_pwr_corrected = dot(omg_c,m_c);

% translational power generated/dissipated at each face:
trans_pwr = dot(v_com_c,f_c);
% f_c(:,trans_pwr > 0) = 0;
trans_pwr_corrected = dot(v_com_c,f_c);

varargout{1} = sum(rot_pwr_corrected);
varargout{2} = sum(trans_pwr_corrected);
varargout{3} = f_c;
varargout{4} = center_c;

%% Compute wrench
% moment components:
F_c(1) = sum(m_c(1,:),'omitnan');
F_c(2) = sum(m_c(2,:),'omitnan');
F_c(3) = sum(m_c(3,:),'omitnan');

% force components:
F_c(4) = sum(f_c(1,:),'omitnan');
F_c(5) = sum(f_c(2,:),'omitnan');
F_c(6) = sum(f_c(3,:),'omitnan');

F_c = F_c(:); % make wrench a column vector
end